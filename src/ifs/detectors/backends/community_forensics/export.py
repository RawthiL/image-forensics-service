"""Export a Community Forensics checkpoint to ONNX, and to a Triton model repository.

Needs torch; run it once, offline, on a machine that has the `community-forensics`
extra. The serving containers never need torch as a result.

    python -m ifs.detectors.backends.community_forensics.export \\
        --model commfor-384 --out-dir ./weights

Writes:
    <out-dir>/onnx/<model>.onnx                      for the onnx backend
    <out-dir>/triton/<model>/1/model.onnx            for the triton backend
    <out-dir>/triton/<model>/config.pbtxt

The upstream project publishes safetensors only, which is why this is a local
step rather than a catalog download.
"""

from __future__ import annotations

import argparse
import inspect
import pathlib
import sys

INPUT_NAME = "pixel_values"
OUTPUT_NAME = "logit"

CONFIG_PBTXT = """\
# Generated by ifs.detectors.backends.community_forensics.export -- do not edit.
name: "{name}"
platform: "onnxruntime_onnx"
max_batch_size: {max_batch}
input [
  {{
    name: "{input_name}"
    data_type: TYPE_FP32
    dims: [ 3, {size}, {size} ]
  }}
]
output [
  {{
    name: "{output_name}"
    data_type: TYPE_FP32
    dims: [ 1 ]
  }}
]
dynamic_batching {{
  max_queue_delay_microseconds: {delay}
}}
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--model", default="commfor-384", help="catalog model name")
    ap.add_argument("--out-dir", default="./weights", help="weights directory root")
    ap.add_argument("--opset", type=int, default=17)
    ap.add_argument("--max-batch", type=int, default=16, help="Triton max_batch_size")
    ap.add_argument(
        "--batch-delay-us", type=int, default=2000, help="Triton dynamic batching queue delay"
    )
    ap.add_argument("--weights-dir", default=None, help="where the safetensors checkpoint lives")
    args = ap.parse_args(argv)

    try:
        import torch
    except ImportError:
        print(
            "error: export needs torch. Install the export extra:\n"
            "    uv sync --extra cpu --extra community-forensics",
            file=sys.stderr,
        )
        return 2


    from .catalog import resolve_model, resolve_variant
    from .detector import CommunityForensicsDetector

    entry = resolve_model(args.model)
    variant = resolve_variant(entry.variant)

    det = CommunityForensicsDetector(
        model=args.model, device="cpu", dtype="float32", weights_dir=args.weights_dir
    )
    det.warmup()
    net = det._net
    assert net is not None
    net.eval()

    root = pathlib.Path(args.out_dir).expanduser()
    onnx_path = root / "onnx" / f"{args.model}.onnx"
    triton_path = root / "triton" / args.model / "1" / "model.onnx"
    for p in (onnx_path, triton_path):
        p.parent.mkdir(parents=True, exist_ok=True)

    size = variant.input_size
    export_kwargs = dict(
        input_names=[INPUT_NAME],
        output_names=[OUTPUT_NAME],
        dynamic_axes={INPUT_NAME: {0: "batch"}, OUTPUT_NAME: {0: "batch"}},
        opset_version=args.opset,
        do_constant_folding=True,
    )
    # torch >= 2.9 exports through the dynamo path, which writes weights to a
    # sibling `.onnx.data` file by default. That silently breaks anything that
    # copies only the .onnx -- including the Triton model repository below --
    # so force a single self-contained file. The flag does not exist on the
    # older TorchScript exporter, which already writes one file.
    if "external_data" in inspect.signature(torch.onnx.export).parameters:
        export_kwargs["external_data"] = False

    torch.onnx.export(net, torch.zeros(1, 3, size, size), str(onnx_path), **export_kwargs)

    stray = onnx_path.with_suffix(onnx_path.suffix + ".data")
    if stray.exists():
        raise SystemExit(
            f"error: the exporter still wrote external weights to {stray}. "
            f"The artifact must be a single self-contained file."
        )
    print(f"wrote {onnx_path} ({onnx_path.stat().st_size / 1e6:.1f} MB)")

    # Verify before publishing: an export that disagrees with the checkpoint is
    # worse than no export, because the fingerprint would claim they match.
    _assert_signature(onnx_path, size)
    _verify(net, onnx_path, size)

    triton_path.write_bytes(onnx_path.read_bytes())
    cfg = triton_path.parent.parent / "config.pbtxt"
    cfg.write_text(
        CONFIG_PBTXT.format(
            name=args.model,
            size=size,
            max_batch=args.max_batch,
            delay=args.batch_delay_us,
            input_name=INPUT_NAME,
            output_name=OUTPUT_NAME,
        )
    )
    print(f"wrote {triton_path}")
    print(f"wrote {cfg}")
    print(
        f"\nonnx backend : detector.model: {args.model}  +  weights.dir: {args.out_dir}\n"
        f"triton backend: point Triton at {root / 'triton'} and set\n"
        f"                detector.options: {{model_name: {args.model}, "
        f"variant: {entry.variant}, url: 'http://triton:8000'}}"
    )
    return 0


def _assert_signature(onnx_path: pathlib.Path, size: int) -> None:
    """The graph must expose the tensor names the backends and config.pbtxt use.

    torch has more than one ONNX exporter and they have not always honored
    `input_names`/`output_names` identically. A renamed tensor would produce an
    artifact that loads fine and then fails at inference, so check it here.
    """
    try:
        import onnxruntime as ort
    except ImportError:
        print("note: onnxruntime not installed, skipping signature check", file=sys.stderr)
        return

    sess = ort.InferenceSession(str(onnx_path), providers=["CPUExecutionProvider"])
    got_in = [i.name for i in sess.get_inputs()]
    got_out = [o.name for o in sess.get_outputs()]
    if got_in != [INPUT_NAME] or got_out != [OUTPUT_NAME]:
        raise SystemExit(
            f"error: exported graph has inputs={got_in} outputs={got_out}, but the "
            f"backends and config.pbtxt expect ['{INPUT_NAME}'] / ['{OUTPUT_NAME}']. "
            f"The torch exporter renamed them."
        )
    shape = sess.get_inputs()[0].shape
    if list(shape[1:]) != [3, size, size]:
        raise SystemExit(
            f"error: exported input shape is {shape}, expected [batch, 3, {size}, {size}]"
        )
    print(f"signature ok: {got_in[0]} {shape} -> {got_out[0]}")


def _verify(net, onnx_path: pathlib.Path, size: int) -> None:
    try:
        import onnxruntime as ort
    except ImportError:
        print("note: onnxruntime not installed, skipping parity check", file=sys.stderr)
        return
    import numpy as np
    import torch

    torch.manual_seed(0)
    x = torch.randn(3, 3, size, size)
    with torch.inference_mode():
        ref = torch.sigmoid(net(x).float()).numpy().reshape(-1)
    sess = ort.InferenceSession(str(onnx_path), providers=["CPUExecutionProvider"])
    got = sess.run(None, {"pixel_values": x.numpy()})[0].reshape(-1)
    got = 1.0 / (1.0 + np.exp(-got))
    diff = float(np.max(np.abs(got - ref)))
    print(f"parity vs torch: max|diff| = {diff:.2e}")
    if diff > 1e-4:
        raise SystemExit(f"error: ONNX export disagrees with the checkpoint ({diff:.2e})")


if __name__ == "__main__":
    raise SystemExit(main())
